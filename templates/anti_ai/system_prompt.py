def get_anti_ai_system_prompt(style_prompt: str = "") -> str:
    """
    組合反AI系統提示詞
    
    Args:
        style_prompt: 風格特定的系統提示詞
        
    Returns:
        完整的系統提示詞
    """
    parts = []
    
    # 風格提示詞（如果有）
    if style_prompt:
        parts.append(style_prompt)
    
    # 核心反AI規則
    parts.append(CORE_ANTI_AI_RULES)
    
    # 繁體中文規範
    parts.append(TRADITIONAL_CHINESE_RULES)
    
    return "\n\n".join(parts)


